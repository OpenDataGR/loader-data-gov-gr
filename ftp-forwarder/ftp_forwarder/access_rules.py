"""The whitelist and blacklist from loader's Security box, enforced on this box.

Loader sends the active rules in the reply to every heartbeat (``access``:
``version``, ``allow``, ``block``) and this module applies them:

* **block (blacklist)** -- the source address is dropped at the firewall: a
  dedicated iptables chain, ``LOADER-ACCESS``, jumped to first in ``INPUT``. It
  covers every port (FTP, SFTP, SSH), not just the ones with a login to guess.
* **allow (whitelist)** -- the address is never banned: it goes into fail2ban's
  ``ignoreip`` for every jail (a generated ``jail.d`` file), any ban it
  currently has is lifted, and, inside the same chain, a ``RETURN`` rule comes
  *before* the drops, so a trusted address inside a blocked range is not dropped.

Applied at most once per version of the rules (the heartbeat reports the version
applied, loader shows "applied" or "waiting"), and again after a restart, since
the chain lives in memory and the process starts with nothing applied.

This is config for a root process built from data that crossed the network, so it
is checked here independently of loader: IPv4 only, nothing narrower than a /8
(a mistake must not blackhole or whitelist the internet), nothing overlapping
loopback, a size cap -- and any bad entry refuses the whole set, leaving what is
in force untouched. Commands are argument lists, never a shell. ``run`` is
injectable so tests need no iptables or fail2ban.
"""

from __future__ import annotations

import dataclasses
import ipaddress
import logging
import os
import re
import subprocess
from typing import Callable, Iterable

from ftp_forwarder import box_health

logger = logging.getLogger(__name__)

F2B_CONF_PATH = "/etc/fail2ban/jail.d/zz-loader-access.local"  # "zz": read after, so it overrides, the per-jail files
CHAIN = "LOADER-ACCESS"
MIN_PREFIX = 8
MAX_ENTRIES = 500
_BASE_IGNORE = "127.0.0.1/8 ::1"
_LOOPBACK = ipaddress.ip_network("127.0.0.0/8")
_VERSION = re.compile(r"^[A-Za-z0-9]{1,64}$")

Runner = Callable[[list[str]], subprocess.CompletedProcess]


class AccessError(RuntimeError):
    pass


@dataclasses.dataclass(frozen=True)
class Access:
    version: str
    allow: tuple[str, ...] = ()
    block: tuple[str, ...] = ()


def _default_run(cmd: list[str]) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, capture_output=True, text=True, timeout=30)


def _canonical(entry: object, list_name: str) -> str:
    try:
        network = ipaddress.ip_network(str(entry).strip(), strict=False)
    except ValueError as exc:
        raise AccessError("%s: not an address or range: %r" % (list_name, entry)) from exc
    if network.version != 4:
        raise AccessError("%s: only IPv4 is supported, got %r" % (list_name, entry))
    if network.prefixlen < MIN_PREFIX:
        raise AccessError("%s: %s is wider than a /%d" % (list_name, network, MIN_PREFIX))
    if network.overlaps(_LOOPBACK):
        raise AccessError("%s: %s overlaps loopback" % (list_name, network))
    return str(network)


def parse(body: object) -> Access | None:
    """The ``access`` object from loader's reply, validated. None when the reply
    carries none (an older loader). Raises ``AccessError`` for one that is
    malformed, so nothing from it is applied."""
    if body is None:
        return None
    if not isinstance(body, dict):
        raise AccessError("access rules are not an object")
    version = body.get("version")
    if not isinstance(version, str) or not _VERSION.match(version):
        raise AccessError("access rules have no usable version")
    lists = {}
    for name in ("allow", "block"):
        entries = body.get(name, [])
        if not isinstance(entries, list):
            raise AccessError("%s is not a list" % name)
        if len(entries) > MAX_ENTRIES:
            raise AccessError("%s has more than %d entries" % (name, MAX_ENTRIES))
        lists[name] = tuple(sorted({_canonical(e, name) for e in entries}))
    return Access(version=version, allow=lists["allow"], block=lists["block"])


def render_fail2ban(allow: Iterable[str], jails: Iterable[str]) -> str:
    ignore = " ".join([_BASE_IGNORE, *allow])
    out = [
        "# Generated by the account-sync service from loader's Security box whitelist.",
        "# Do not edit: it is rewritten whenever the whitelist changes.",
    ]
    for jail in jails:
        out += ["[%s]" % jail, "ignoreip = %s" % ignore]
    return "\n".join(out) + "\n"


def _read(path: str) -> str | None:
    try:
        with open(path, encoding="utf-8") as fh:
            return fh.read()
    except FileNotFoundError:
        return None


def _write(path: str, content: str) -> None:
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write(content)
    os.chmod(tmp, 0o644)
    os.replace(tmp, path)


class Enforcer:
    def __init__(
        self,
        *,
        jails: Iterable[str] = box_health.DEFAULT_JAILS,
        f2b_conf: str = F2B_CONF_PATH,
        chain: str = CHAIN,
        run: Runner = _default_run,
    ):
        self._jails = tuple(jails)
        self._f2b_conf = f2b_conf
        self._chain = chain
        self._run = run
        self.applied_version: str | None = None

    def _must(self, cmd: list[str], what: str) -> None:
        try:
            result = self._run(cmd)
        except (OSError, subprocess.SubprocessError) as exc:
            raise AccessError("%s: %s" % (what, exc)) from exc
        if result.returncode != 0:
            raise AccessError("%s: %s" % (what, (result.stderr or result.stdout or "failed").strip()[:300]))

    def _firewall(self, access: Access) -> None:
        chain = self._chain
        if self._run(["iptables", "-S", chain]).returncode != 0:  # no such chain yet
            self._must(["iptables", "-N", chain], "creating the %s chain" % chain)
        if self._run(["iptables", "-C", "INPUT", "-j", chain]).returncode != 0:
            self._must(["iptables", "-I", "INPUT", "1", "-j", chain], "hooking the %s chain into INPUT" % chain)
        self._must(["iptables", "-F", chain], "clearing the %s chain" % chain)
        # Trusted first: RETURN leaves the chain, so a whitelisted address inside a blocked range is not dropped.
        for cidr in access.allow:
            self._must(["iptables", "-A", chain, "-s", cidr, "-j", "RETURN"], "allowing %s" % cidr)
        for cidr in access.block:
            self._must(["iptables", "-A", chain, "-s", cidr, "-j", "DROP"], "blocking %s" % cidr)

    def _whitelist(self, access: Access) -> None:
        wanted = render_fail2ban(access.allow, self._jails)
        if _read(self._f2b_conf) != wanted:
            _write(self._f2b_conf, wanted)
            self._must(["fail2ban-client", "reload"], "reloading fail2ban with the new whitelist")
        # A trusted address that is banned right now should not stay banned until its ban runs out.
        banned = box_health.read_banned_in(self._jails, run=self._run) or []
        networks = [ipaddress.ip_network(c) for c in access.allow]
        for address in banned:
            try:
                ip = ipaddress.ip_address(address)
            except ValueError:
                continue
            if any(ip in net for net in networks):
                if box_health.unban_everywhere(address, self._jails, run=self._run):
                    logger.info("lifted the ban on whitelisted %s", address)

    def apply(self, access: Access) -> bool:
        """Bring this box in line with ``access``. True if anything was applied,
        False if this version already is. Raises ``AccessError`` otherwise; the
        version then stays unapplied, so the next heartbeat retries the lot."""
        if access.version == self.applied_version:
            return False
        try:
            self._firewall(access)  # the part that protects: first
            self._whitelist(access)
        except (OSError, subprocess.SubprocessError) as exc:  # e.g. iptables or fail2ban-client is not installed
            raise AccessError("could not run a firewall command: %s" % exc) from exc
        self.applied_version = access.version
        logger.info("applied access rules %s (%d whitelisted, %d blacklisted)", access.version, len(access.allow), len(access.block))
        return True
