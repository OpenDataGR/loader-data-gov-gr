"""Per-account login limits: an account with allowed addresses set in
loader's admin panel may log in from those addresses only.

Enforced by ProFTPD itself -- ``<IfUser name>`` + ``<Limit LOGIN>`` with
``Allow ... / DenyAll`` inside ``<Global>`` -- from a file this module
generates out of the account list the sync already fetches. Proven on this
box (throwaway server on spare ports, 2026-10-02) to bind both plain FTP
and mod_sftp: the account limited to the connecting address got in, the one
limited to another address was refused with the right password, an account
with no limit got in. (``mod_wrap2_sql`` does not cover SFTP, which is why
this is not done that way.)

An account with no allowed addresses has no rule at all, i.e. works from
anywhere, exactly as before this existed.

The generated file is config that runs as root, built from data that came over
the network, so it is built defensively: usernames and addresses are
re-validated here (loader validates too -- this is the second, independent
check), and any bad value fails the whole apply and leaves the previous file in
force, never a half-written or silently weaker one. A new file is only kept if
``proftpd -t`` accepts the whole configuration with it, and ProFTPD is only
reloaded when the content actually changed.

``run`` is injectable so tests need no ProFTPD.
"""

from __future__ import annotations

import ipaddress
import logging
import os
import re
import subprocess
from typing import Callable, Iterable

logger = logging.getLogger(__name__)

# Sorts before loader-sftp.conf, so the <Global> comes first like in the proof.
DEFAULT_CONF_PATH = "/etc/proftpd/conf.d/loader-ip-limits.conf"

# What loader allows for a username (3-32 letters, digits, - and _) -- re-checked
# here because it ends up inside a config file read by a root process.
_MAPPED = ipaddress.ip_network("::ffff:0:0/96")
_USERNAME = re.compile(r"^[A-Za-z0-9_-]{3,32}$")

_HEADER = (
    "# Generated by the account-sync service from the admin panel's \"Allowed from\" lists.\n"
    "# Do not edit: it is rewritten whenever the lists change.\n"
)

Runner = Callable[[list[str]], subprocess.CompletedProcess]


class IpLimitError(RuntimeError):
    pass


def _default_run(cmd: list[str]) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, capture_output=True, text=True, timeout=30)


def _canonical(entry: object) -> str:
    """One allowed address as ProFTPD's ``Allow`` wants it: a host without a
    prefix, a range in CIDR form. IPv4 or IPv6 (ProFTPD takes both when it runs with
    ``UseIPv6 on``, which ``proftpd -t`` enforces; without it an IPv6 entry is a fatal
    config error, never a silent no-op, which would lock the account out). IPv4-mapped
    IPv6 is refused: the IPv4 address is what to write."""
    try:
        network = ipaddress.ip_network(str(entry).strip(), strict=False)
    except ValueError as exc:
        raise IpLimitError("not an address or range: %r" % (entry,)) from exc
    if network.version == 6 and network.overlaps(_MAPPED):
        raise IpLimitError("an IPv4 address written as IPv6 is not accepted, got %r" % (entry,))
    return str(network.network_address) if network.prefixlen == network.max_prefixlen else str(network)


def render(accounts: Iterable[dict]) -> str:
    blocks = []
    for account in sorted(accounts, key=lambda a: str(a.get("username"))):
        entries = account.get("allowed_ips") or []
        if not entries:
            continue  # no limit: no rule
        username = account.get("username")
        if not isinstance(username, str) or not _USERNAME.match(username):
            raise IpLimitError("not a usable username: %r" % (username,))
        allowed = sorted({_canonical(e) for e in entries}, key=lambda a: (ipaddress.ip_network(a).version, ipaddress.ip_network(a).network_address, a))
        blocks.append(
            "  <IfUser %s>\n"
            "    <Limit LOGIN>\n"
            "      Allow %s\n"
            "      DenyAll\n"
            "    </Limit>\n"
            "  </IfUser>\n" % (username, " ".join(allowed))
        )
    if not blocks:
        return _HEADER
    return _HEADER + "<Global>\n" + "".join(blocks) + "</Global>\n"


def _read(path: str) -> str | None:
    try:
        with open(path, encoding="utf-8") as fh:
            return fh.read()
    except FileNotFoundError:
        return None


def _write(path: str, content: str | None) -> None:
    if content is None:
        try:
            os.remove(path)
        except FileNotFoundError:
            pass
        return
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write(content)
    os.chmod(tmp, 0o644)  # ProFTPD reads it; nothing in it is secret
    os.replace(tmp, path)


def apply(
    accounts: Iterable[dict],
    conf_path: str = DEFAULT_CONF_PATH,
    *,
    run: Runner = _default_run,
    proftpd_unit: str = "proftpd",
) -> bool:
    """Bring the file in line with ``accounts``. Returns True if ProFTPD was
    reloaded (the rules changed), False if there was nothing to do. Raises
    ``IpLimitError`` -- with the previous file back in place -- if the new one
    is invalid or ProFTPD would not take it."""
    new = render(accounts)  # raises before anything is touched
    old = _read(conf_path)
    if old == new:
        return False

    _write(conf_path, new)
    try:
        check = run(["proftpd", "-t"])
        if check.returncode != 0:
            raise IpLimitError("proftpd -t rejected the new limits: %s" % (check.stderr or check.stdout or "").strip()[:300])
        reload = run(["systemctl", "reload", proftpd_unit])
        if reload.returncode != 0:
            raise IpLimitError("could not reload %s: %s" % (proftpd_unit, (reload.stderr or "").strip()[:300]))
    except Exception:
        # Put the previous file back so what is on disk is what ProFTPD is
        # running, and the next cycle tries again rather than thinking it is done.
        _write(conf_path, old)
        raise
    logger.info("applied per-account login limits (%d account(s) limited)", new.count("<IfUser "))
    return True
